  CarIcon,
  CircleDotIcon,
  CloudFogIcon,
  CloudIcon,
  CrownIcon,
  DropletIcon,
  EarthIcon,
  FlameIcon,
  FlowerIcon,
  HexagonIcon,
  LighthouseIcon,
  MapIcon,
  MedalIcon,
  MilestoneIcon,
  MoonIcon,
  MoonStarIcon,
  MountainIcon,
  MountainSnowIcon,
  OrbitIcon,
  PickaxeIcon,
  RocketIcon,
  RouteIcon,
  ShellIcon,
  SignpostIcon,
  SnowflakeIcon,
  SparklesIcon,
  SunIcon,
  SunriseIcon,
  TentIcon,
  ThermometerSunIcon,
